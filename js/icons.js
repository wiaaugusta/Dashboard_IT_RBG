/**
 * Ikon SVG lokal berdasarkan nama.
 *
 * @param {string} name - key pada PATHS (mis. "database", "map-pin").
 * @param {{
 *   size?: number,
 *   className?: string,
 *   strokeWidth?: number,
 *   color?: string,
 *   fill?: string,
 *   title?: string,
 *   label?: string
 * }} [options]
 *   - size: ukuran px (default 20).
 *   - strokeWidth: ketebalan garis (default 1.8, konsisten dengan ikon lama).
 *   - color: warna stroke; default "currentColor" agar ikut tema CSS.
 *   - fill: isi bobot; default "none" (gaya outline Lucide).
 *   - title/label: bila diisi, ikon diberi role="img" + <title> untuk a11y.
 * @returns {string} markup <svg> siap disisipkan lewat innerHTML.
 */
export function icon(name, options = {}) {
  const size = options.size || 20;
  const className = options.className || "";
  const strokeWidth = options.strokeWidth || 1.8;
  const color = options.color || "currentColor";
  const fill = options.fill || "none";
  const label = options.label || options.title || "";
  const body = PATHS[name] || PATHS.dashboard;

  const a11y = label
    ? `role="img" aria-label="${escapeAttr(label)}" focusable="false"`
    : 'aria-hidden="true" focusable="false"';
  const title = label ? `<title>${escapeText(label)}</title>` : "";

  return `<svg class="icon ${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="${fill}" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${title}${body}</svg>`;
}

function escapeAttr(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function escapeText(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
